//! Reads just enough of a user-signed transaction to route it (contract §2.7 step 1):
//! the fee payer (the MM) and the `nonce` of its open_position / open_asset_position
//! instruction. The desk does every economic check; this only has to be unambiguous.

use base64::Engine;
use base64::engine::general_purpose::STANDARD as B64;
use solana_transaction::Transaction;

pub const OPEN_POSITION_DISCRIMINATOR: [u8; 8] = [135, 128, 47, 77, 15, 152, 240, 49];
pub const OPEN_ASSET_POSITION_DISCRIMINATOR: [u8; 8] = [120, 227, 20, 71, 252, 225, 87, 70];
/// discriminator 8 + product 1 + fixed_price 8 + expiry_ts 8 + amount 8 + yield_amount 8.
const NONCE_OFFSET: usize = 41;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OpenKind {
    Sol,
    Asset,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OpenTx {
    pub fee_payer: String,
    pub nonce: u64,
    pub kind: OpenKind,
}

/// Parses base64 wire bytes; the error is the `<why>` of "invalid transaction: <why>".
pub fn parse_open_tx(tx_base64: &str, program_id: &str) -> Result<OpenTx, String> {
    let bytes = B64
        .decode(tx_base64.trim())
        .map_err(|_| "tx_base64 is not valid base64".to_string())?;
    if is_versioned(&bytes)? {
        return Err("versioned transactions are not supported".into());
    }
    let tx: Transaction = wincode::deserialize_exact(&bytes)
        .map_err(|e| format!("transaction does not deserialize: {e}"))?;
    let keys = &tx.message.account_keys;
    let fee_payer = keys
        .first()
        .ok_or("transaction has no account keys")?
        .to_string();

    for ix in &tx.message.instructions {
        let Some(program) = keys.get(usize::from(ix.program_id_index)) else {
            return Err("instruction program index out of range".into());
        };
        if program.to_string() != program_id {
            continue;
        }
        let kind = match ix.data.get(..8) {
            Some(d) if d == OPEN_POSITION_DISCRIMINATOR => OpenKind::Sol,
            Some(d) if d == OPEN_ASSET_POSITION_DISCRIMINATOR => OpenKind::Asset,
            _ => continue,
        };
        let nonce = ix
            .data
            .get(NONCE_OFFSET..NONCE_OFFSET + 8)
            .and_then(|b| <[u8; 8]>::try_from(b).ok())
            .map(u64::from_le_bytes)
            .ok_or("open_position data is too short")?;
        return Ok(OpenTx {
            fee_payer,
            nonce,
            kind,
        });
    }
    Err("no open_position instruction for the program".into())
}

/// Skips the compact-u16 signature count and the signatures; a message whose first
/// byte has the high bit set is a versioned (v0+) message.
fn is_versioned(bytes: &[u8]) -> Result<bool, String> {
    let (count, len) = decode_compact_u16(bytes).ok_or("truncated signature count")?;
    let offset = len + count * 64;
    let first = bytes.get(offset).ok_or("truncated transaction")?;
    Ok(*first >= 0x80)
}

/// Solana's short-vec length: 7 bits per byte, little-endian, at most 3 bytes.
fn decode_compact_u16(bytes: &[u8]) -> Option<(usize, usize)> {
    let mut value = 0usize;
    for i in 0..3 {
        let b = *bytes.get(i)?;
        value |= usize::from(b & 0x7f) << (7 * i);
        if b & 0x80 == 0 {
            return (value <= usize::from(u16::MAX)).then_some((value, i + 1));
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::Value;

    // Generated by tests/fixtures/gen-fixtures.mjs with the desk's BreezepocketClient.
    const FIXTURES: &str = include_str!("../tests/fixtures/transactions.json");
    const PROGRAM: &str = "BeytdpJYSGP1oFRxEiBLkSRGuW6HW3Pk9dqSZCuSteQ9";

    fn case(name: &str) -> (String, String, Option<u64>) {
        let fx: Value = serde_json::from_str(FIXTURES).unwrap();
        let c = &fx["cases"][name];
        (
            c["tx_base64"].as_str().unwrap().to_string(),
            c["fee_payer"].as_str().unwrap().to_string(),
            c["nonce"].as_str().map(|n| n.parse().unwrap()),
        )
    }

    #[test]
    fn parses_desk_built_transactions() {
        for (name, kind) in [
            ("open_position_sol", OpenKind::Sol),
            ("open_asset_position", OpenKind::Asset),
            ("compute_budget_prefixed", OpenKind::Sol),
            ("open_position_mm_b", OpenKind::Sol),
        ] {
            let (tx, fee_payer, nonce) = case(name);
            let parsed = parse_open_tx(&tx, PROGRAM).unwrap_or_else(|e| panic!("{name}: {e}"));
            assert_eq!(
                parsed,
                OpenTx {
                    fee_payer,
                    nonce: nonce.unwrap(),
                    kind
                },
                "{name}"
            );
        }
    }

    #[test]
    fn large_nonce_is_little_endian() {
        let (tx, _, _) = case("open_asset_position");
        assert_eq!(
            parse_open_tx(&tx, PROGRAM).unwrap().nonce,
            0xfedc_ba98_7654_3210
        );
    }

    #[test]
    fn rejects_versioned_transactions() {
        let (tx, _, _) = case("versioned_v0");
        assert_eq!(
            parse_open_tx(&tx, PROGRAM).unwrap_err(),
            "versioned transactions are not supported"
        );
    }

    #[test]
    fn rejects_transactions_without_open_position() {
        let (tx, _, _) = case("transfer_only");
        assert!(
            parse_open_tx(&tx, PROGRAM)
                .unwrap_err()
                .contains("no open_position")
        );
        // Right bytes, other program.
        let (tx, _, _) = case("open_position_sol");
        assert!(
            parse_open_tx(&tx, "11111111111111111111111111111111")
                .unwrap_err()
                .contains("no open_position")
        );
    }

    #[test]
    fn rejects_garbage() {
        assert!(
            parse_open_tx("!!!", PROGRAM)
                .unwrap_err()
                .contains("base64")
        );
        assert!(parse_open_tx("", PROGRAM).is_err());
        assert!(parse_open_tx(&B64.encode([1u8]), PROGRAM).is_err());
        assert!(parse_open_tx(&B64.encode([0xffu8, 0xff, 0xff, 0xff]), PROGRAM).is_err());
        let (tx, _, _) = case("open_position_sol");
        let mut bytes = B64.decode(tx).unwrap();
        bytes.truncate(bytes.len() - 10);
        assert!(
            parse_open_tx(&B64.encode(&bytes), PROGRAM)
                .unwrap_err()
                .contains("deserialize")
        );
        bytes.extend_from_slice(&[0u8; 20]);
        assert!(
            parse_open_tx(&B64.encode(&bytes), PROGRAM).is_err(),
            "trailing bytes are rejected"
        );
    }

    #[test]
    fn compact_u16() {
        assert_eq!(decode_compact_u16(&[0x02]), Some((2, 1)));
        assert_eq!(decode_compact_u16(&[0x80, 0x01]), Some((128, 2)));
        assert_eq!(decode_compact_u16(&[0xff, 0xff, 0x03]), Some((65535, 3)));
        assert_eq!(decode_compact_u16(&[0x80]), None);
        assert_eq!(decode_compact_u16(&[0xff, 0xff, 0xff]), None);
    }
}
