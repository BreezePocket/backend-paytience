//! `hello` verification (contract §1.2, §5.5), in the contract's order: version,
//! channel, registration (status `approved`), signature, then program id and mint.
//! Each failure carries its close code.

use base64::Engine;
use base64::engine::general_purpose::STANDARD as B64;
use ed25519_dalek::{Signature, VerifyingKey};
use serde_json::Value;

use crate::mmreg::MmRegistry;
use crate::protocol::{Channel, auth_message};

/// Bad hello, signature, version or channel; also the hello timeout.
pub const CLOSE_BAD_HELLO: u16 = 4001;
/// No approved registration (§5.5); also closes the sockets of an MM that an admin
/// rejected, suspended or deleted (§5.4).
pub const CLOSE_NOT_APPROVED: u16 = 4003;
pub const CLOSE_MISMATCH: u16 = 4009;
pub const CLOSE_REPLACED: u16 = 4000;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AuthError {
    pub code: u16,
    pub reason: String,
}

fn fail(code: u16, reason: impl Into<String>) -> AuthError {
    AuthError {
        code,
        reason: reason.into(),
    }
}

/// What the backend checks a hello against.
pub struct Expected<'a> {
    pub channel: Channel,
    pub challenge: &'a str,
    pub mms: &'a MmRegistry,
    pub program_id: &'a str,
    pub usdc_mint: &'a str,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Authenticated {
    pub mm_pubkey: String,
    pub instance_id: String,
    pub name: String,
}

const MAX_INSTANCE_ID_LEN: usize = 128;

pub fn verify_hello(hello: &Value, expected: &Expected<'_>) -> Result<Authenticated, AuthError> {
    let field = |k: &str| hello.get(k).and_then(Value::as_str);

    if hello.get("version").and_then(Value::as_u64) != Some(1) {
        return Err(fail(CLOSE_BAD_HELLO, "unsupported version (expected 1)"));
    }
    let channel = expected.channel.as_str();
    if field("channel") != Some(channel) {
        return Err(fail(
            CLOSE_BAD_HELLO,
            format!("channel mismatch: this is {channel}"),
        ));
    }
    let Some(mm_pubkey) = field("mm_pubkey") else {
        return Err(fail(CLOSE_BAD_HELLO, "bad hello: mm_pubkey is required"));
    };
    let Some(name) = expected.mms.approved_name(mm_pubkey) else {
        return Err(fail(
            CLOSE_NOT_APPROVED,
            format!("{mm_pubkey} is not an approved market maker"),
        ));
    };
    let instance_id = match field("instance_id") {
        Some(id) if !id.is_empty() && id.len() <= MAX_INSTANCE_ID_LEN => id,
        _ => return Err(fail(CLOSE_BAD_HELLO, "bad hello: instance_id is required")),
    };
    let message = auth_message(expected.channel, expected.challenge);
    if !signature_valid(
        mm_pubkey,
        field("signature").unwrap_or_default(),
        message.as_bytes(),
    ) {
        return Err(fail(CLOSE_BAD_HELLO, "bad signature"));
    }
    if field("program_id") != Some(expected.program_id) {
        return Err(fail(
            CLOSE_MISMATCH,
            format!("program_id mismatch: backend uses {}", expected.program_id),
        ));
    }
    if field("usdc_mint") != Some(expected.usdc_mint) {
        return Err(fail(
            CLOSE_MISMATCH,
            format!("usdc_mint mismatch: backend uses {}", expected.usdc_mint),
        ));
    }
    Ok(Authenticated {
        mm_pubkey: mm_pubkey.to_string(),
        instance_id: instance_id.to_string(),
        name,
    })
}

/// ed25519 over `message` by the base58 `pubkey`, with a base64 `signature`.
pub fn signature_valid(pubkey: &str, signature_b64: &str, message: &[u8]) -> bool {
    let Ok(key_bytes) = bs58::decode(pubkey).into_vec() else {
        return false;
    };
    let Ok(key_bytes) = <[u8; 32]>::try_from(key_bytes.as_slice()) else {
        return false;
    };
    let Ok(key) = VerifyingKey::from_bytes(&key_bytes) else {
        return false;
    };
    let Ok(sig_bytes) = B64.decode(signature_b64) else {
        return false;
    };
    let Ok(sig_bytes) = <[u8; 64]>::try_from(sig_bytes.as_slice()) else {
        return false;
    };
    key.verify_strict(message, &Signature::from_bytes(&sig_bytes))
        .is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::mmreg::{Caps, MmRecord};
    use ed25519_dalek::{Signer, SigningKey};
    use serde_json::json;

    // Generated by tests/fixtures/gen-fixtures.mjs with node:crypto (PKCS8-wrapped seed 0x01).
    const AUTH_FIXTURE: &str = include_str!("../tests/fixtures/auth.json");
    const PROGRAM: &str = "BeytdpJYSGP1oFRxEiBLkSRGuW6HW3Pk9dqSZCuSteQ9";
    const MINT: &str = "EdmxWPmx2WH6WgFfTdu9xfkYf3k1g5wD1zccTVySEEh1";
    const CHALLENGE: &str = "00112233445566778899aabbccddeeff00112233445566778899aabbccddeeff";

    fn key() -> SigningKey {
        SigningKey::from_bytes(&[1u8; 32])
    }

    fn pubkey(k: &SigningKey) -> String {
        bs58::encode(k.verifying_key().as_bytes()).into_string()
    }

    fn allowlist(k: &SigningKey) -> MmRegistry {
        MmRegistry::in_memory(vec![MmRecord::approved(
            pubkey(k),
            "alpha",
            Caps::new(1000.0, &[("SOL", 1000.0)]),
        )])
    }

    fn hello(k: &SigningKey, channel: &str, signed_channel: Channel) -> Value {
        let sig = k.sign(auth_message(signed_channel, CHALLENGE).as_bytes());
        json!({
            "type": "hello", "version": 1, "channel": channel, "mm_pubkey": pubkey(k),
            "instance_id": "inst-1", "program_id": PROGRAM, "usdc_mint": MINT,
            "signature": B64.encode(sig.to_bytes()),
        })
    }

    fn check(h: &Value, list: &MmRegistry, channel: Channel) -> Result<Authenticated, AuthError> {
        verify_hello(
            h,
            &Expected {
                channel,
                challenge: CHALLENGE,
                mms: list,
                program_id: PROGRAM,
                usdc_mint: MINT,
            },
        )
    }

    #[test]
    fn accepts_a_valid_hello() {
        let k = key();
        let ok = check(
            &hello(&k, "ws/rfq", Channel::Rfq),
            &allowlist(&k),
            Channel::Rfq,
        )
        .unwrap();
        assert_eq!(
            ok,
            Authenticated {
                mm_pubkey: pubkey(&k),
                instance_id: "inst-1".into(),
                name: "alpha".into()
            }
        );
    }

    #[test]
    fn rejects_in_contract_order() {
        let k = key();
        let list = allowlist(&k);
        let code = |h: &Value, ch: Channel| check(h, &list, ch).unwrap_err().code;

        let mut h = hello(&k, "ws/rfq", Channel::Rfq);
        h["version"] = json!(2);
        h["mm_pubkey"] = json!("unknown");
        assert_eq!(
            code(&h, Channel::Rfq),
            CLOSE_BAD_HELLO,
            "version is checked first"
        );

        // Signed for ws/rfq but dialled ws/sign.
        let h = hello(&k, "ws/rfq", Channel::Rfq);
        assert_eq!(code(&h, Channel::Sign), CLOSE_BAD_HELLO);

        // Not registered beats a bad signature and a mint mismatch.
        let other = SigningKey::from_bytes(&[9u8; 32]);
        let mut h = hello(&other, "ws/rfq", Channel::Rfq);
        h["signature"] = json!("AAAA");
        h["usdc_mint"] = json!("x");
        assert_eq!(code(&h, Channel::Rfq), CLOSE_NOT_APPROVED);

        // Bad signature beats a mint mismatch.
        let mut h = hello(&k, "ws/rfq", Channel::Rfq);
        h["signature"] = json!(B64.encode([0u8; 64]));
        h["usdc_mint"] = json!("x");
        assert_eq!(code(&h, Channel::Rfq), CLOSE_BAD_HELLO);

        // Right channel in the frame, but signed over the other channel's message.
        let h = hello(&k, "ws/sign", Channel::Rfq);
        assert_eq!(code(&h, Channel::Sign), CLOSE_BAD_HELLO);

        let mut h = hello(&k, "ws/rfq", Channel::Rfq);
        h["program_id"] = json!(MINT);
        assert_eq!(code(&h, Channel::Rfq), CLOSE_MISMATCH);
        let mut h = hello(&k, "ws/rfq", Channel::Rfq);
        h["usdc_mint"] = json!(PROGRAM);
        assert_eq!(code(&h, Channel::Rfq), CLOSE_MISMATCH);

        let mut h = hello(&k, "ws/rfq", Channel::Rfq);
        h.as_object_mut().unwrap().remove("instance_id");
        assert_eq!(code(&h, Channel::Rfq), CLOSE_BAD_HELLO);
        let mut h = hello(&k, "ws/rfq", Channel::Rfq);
        h.as_object_mut().unwrap().remove("signature");
        assert_eq!(code(&h, Channel::Rfq), CLOSE_BAD_HELLO);
    }

    #[test]
    fn only_an_approved_registration_may_connect() {
        let k = key();
        let list = allowlist(&k);
        let h = hello(&k, "ws/rfq", Channel::Rfq);
        assert!(check(&h, &list, Channel::Rfq).is_ok());
        list.suspend(&pubkey(&k), 1).unwrap();
        assert_eq!(
            check(&h, &list, Channel::Rfq).unwrap_err().code,
            CLOSE_NOT_APPROVED
        );
        list.approve(&pubkey(&k), &json!({}), 2).unwrap();
        assert!(check(&h, &list, Channel::Rfq).is_ok());
        list.reject(&pubkey(&k), 3).unwrap();
        assert_eq!(
            check(&h, &list, Channel::Rfq).unwrap_err().code,
            CLOSE_NOT_APPROVED
        );
        list.delete(&pubkey(&k)).unwrap();
        assert_eq!(
            check(&h, &list, Channel::Rfq).unwrap_err().code,
            CLOSE_NOT_APPROVED
        );
    }

    #[test]
    fn verifies_node_crypto_signatures() {
        let fx: Value = serde_json::from_str(AUTH_FIXTURE).unwrap();
        let pubkey = fx["pubkey"].as_str().unwrap();
        let challenge = fx["challenge"].as_str().unwrap();
        // Same seed on both sides gives the same key.
        assert_eq!(pubkey, super::tests::pubkey(&key()));
        for (channel, other) in [(Channel::Rfq, Channel::Sign), (Channel::Sign, Channel::Rfq)] {
            let entry = &fx["channels"][channel.as_str()];
            let message = auth_message(channel, challenge);
            assert_eq!(entry["message"].as_str().unwrap(), message);
            let sig = entry["signature"].as_str().unwrap();
            assert!(signature_valid(pubkey, sig, message.as_bytes()));
            assert!(!signature_valid(
                pubkey,
                sig,
                auth_message(other, challenge).as_bytes()
            ));
        }
    }

    #[test]
    fn signature_valid_rejects_garbage() {
        assert!(!signature_valid("not-base58!", "AAAA", b"m"));
        assert!(!signature_valid(&pubkey(&key()), "not base64", b"m"));
        assert!(!signature_valid(
            &pubkey(&key()),
            &B64.encode([1u8; 10]),
            b"m"
        ));
    }
}
