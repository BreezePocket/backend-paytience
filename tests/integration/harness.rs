#[derive(Clone)]
pub struct MmKey {
    pub signing: SigningKey,
    pub pubkey: String,
}

/// Seed 1 is the fixtures' MM A, seed 2 MM B.
pub fn mm_key(seed: u8) -> MmKey {
    let signing = SigningKey::from_bytes(&[seed; 32]);
    let pubkey = bs58::encode(signing.verifying_key().as_bytes()).into_string();
    MmKey { signing, pubkey }
}

pub fn key_a() -> MmKey {
    mm_key(1)
}

pub fn key_b() -> MmKey {
    mm_key(2)
}

