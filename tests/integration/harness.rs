pub struct TestServer {
    pub addr: SocketAddr,
    pub app: Arc<App>,
    pub http: reqwest::Client,
    shutdown: Option<oneshot::Sender<()>>,
}

pub async fn start(config: Config) -> TestServer {
    let app = App::new(config).unwrap();
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let addr = listener.local_addr().unwrap();
    let (tx, rx) = oneshot::channel::<()>();
    tokio::spawn(serve(listener, app.clone(), async move {
        let _ = rx.await;
    }));
    TestServer {
        addr,
        app,
        http: reqwest::Client::new(),
        shutdown: Some(tx),
    }
}

impl TestServer {
    /// Triggers the graceful shutdown `serve` was started with.
    pub fn shutdown(&mut self) {
        if let Some(tx) = self.shutdown.take() {
            let _ = tx.send(());
        }
    }

    pub fn ws_url(&self, path: &str) -> String {
        format!("ws://{}{}", self.addr, path)
    }

    pub fn url(&self, path: &str) -> String {
        format!("http://{}{}", self.addr, path)
    }

    pub async fn get(&self, path: &str) -> (u16, Value) {
        let r = self.http.get(self.url(path)).send().await.unwrap();
        let status = r.status().as_u16();
        (status, r.json().await.unwrap())
    }

    pub async fn post(&self, path: &str, body: &Value) -> (u16, Value) {
        let r = self
            .http
            .post(self.url(path))
            .json(body)
            .send()
            .await
            .unwrap();
        let status = r.status().as_u16();
        (status, r.json().await.unwrap())
    }

    pub async fn rfq(&self, rfq_id: &str, nonce: &str) -> (u16, Value) {
        self.post("/rfq", &rfq_body(rfq_id, nonce)).await
    }

    pub async fn sign(&self, request_id: &str, tx_base64: &str) -> (u16, Value) {
        self.post(
            "/sign",
            &json!({ "type": "sign_request", "request_id": request_id, "tx_base64": tx_base64 }),
        )
        .await
    }

    pub async fn wait_eligible(&self, n: usize) {
        wait_until(
            || self.app.registry.eligible().len() == n,
            "eligible instances",
        )
        .await;
    }

    /// Waits until `n` MMs have a fresh health snapshot.
    pub async fn wait_fresh(&self, n: usize) {
        wait_until(
            || paytience_backend::market::fresh_snapshots(&self.app).len() == n,
            "fresh health",
        )
        .await;
    }
}

pub fn rfq_body(rfq_id: &str, nonce: &str) -> Value {
    json!({ "type": "rfq_request", "rfq_id": rfq_id, "product": "sell_sol", "fixed_price": "250000000",
            "expiry_ts": 1759824000, "amount": "500000000", "user_pubkey": user_pubkey(), "nonce": nonce })
}

pub async fn wait_until(mut cond: impl FnMut() -> bool, what: &str) {
    let deadline = Instant::now() + Duration::from_secs(5);
    while !cond() {
        assert!(Instant::now() < deadline, "timed out waiting for {what}");
        tokio::time::sleep(Duration::from_millis(10)).await;
    }
}

