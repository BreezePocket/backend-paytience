pub enum RpcReply {
    Result(Value),
    Error(String),
}

/// `(method, params, how many earlier calls of this method)` → reply.
pub type RpcScript = Arc<dyn Fn(&str, &Value, usize) -> RpcReply + Send + Sync>;

#[derive(Clone)]
struct ScriptedRpc {
    script: RpcScript,
    calls: Arc<Mutex<Vec<Value>>>,
}

pub struct MockRpc {
    pub url: String,
    calls: Arc<Mutex<Vec<Value>>>,
}

impl MockRpc {
    /// Every request body received for `method`, in order.
    pub fn calls_to(&self, method: &str) -> Vec<Value> {
        self.calls
            .lock()
            .unwrap()
            .iter()
            .filter(|c| c["method"] == method)
            .cloned()
            .collect()
    }
}

async fn scripted_handler(
    axum::extract::State(rpc): axum::extract::State<ScriptedRpc>,
    body: axum::Json<Value>,
) -> axum::Json<Value> {
    let method = body.0["method"].as_str().unwrap_or_default().to_string();
    let seen = {
        let mut calls = rpc.calls.lock().unwrap();
        let seen = calls.iter().filter(|c| c["method"] == method).count();
        calls.push(body.0.clone());
        seen
    };
    let id = body.0["id"].clone();
    axum::Json(match (rpc.script)(&method, &body.0["params"], seen) {
        RpcReply::Result(r) => json!({ "jsonrpc": "2.0", "id": id, "result": r }),
        RpcReply::Error(m) => {
            json!({ "jsonrpc": "2.0", "id": id, "error": { "code": -32002, "message": m } })
        }
    })
}

pub async fn scripted_rpc(
    script: impl Fn(&str, &Value, usize) -> RpcReply + Send + Sync + 'static,
) -> MockRpc {
    let calls = Arc::new(Mutex::new(Vec::new()));
    let app = axum::Router::new()
        .route("/", axum::routing::post(scripted_handler))
        .with_state(ScriptedRpc {
            script: Arc::new(script),
            calls: calls.clone(),
        });
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let addr = listener.local_addr().unwrap();
    tokio::spawn(async move { axum::serve(listener, app).await.unwrap() });
    MockRpc {
        url: format!("http://{addr}/"),
        calls,
    }
}
