/// Next JSON text frame (pings and pongs skipped); None on close or end.
pub async fn next_json(ws: &mut Ws) -> Option<Value> {
    loop {
        match tokio::time::timeout(Duration::from_secs(5), ws.next())
            .await
            .ok()??
        {
            Ok(Message::Text(t)) => return serde_json::from_str(t.as_str()).ok(),
            Ok(Message::Close(_)) | Err(_) => return None,
            Ok(_) => {}
        }
    }
}

/// Reads until the close frame; returns (close code, text frames seen before it).
pub async fn read_until_close(ws: &mut Ws) -> (Option<u16>, Vec<Value>) {
    let mut frames = Vec::new();
    loop {
        match tokio::time::timeout(Duration::from_secs(5), ws.next()).await {
            Err(_) => panic!("no close frame within 5s"),
            Ok(None) | Ok(Some(Err(_))) => return (None, frames),
            Ok(Some(Ok(Message::Close(frame)))) => {
                return (frame.map(|f| u16::from(f.code)), frames);
            }
            Ok(Some(Ok(Message::Text(t)))) => {
                frames.push(serde_json::from_str(t.as_str()).unwrap())
            }
            Ok(Some(Ok(_))) => {}
        }
    }
}

pub async fn send_json(ws: &mut Ws, v: &Value) {
    ws.send(Message::Text(v.to_string().into())).await.unwrap();
}

/// Everything a hello carries; tests break one field at a time.
#[derive(Clone)]
pub struct HelloSpec {
    pub key: MmKey,
    pub instance_id: String,
    pub channel: String,
    pub signed_channel: Channel,
    pub version: Value,
    pub program_id: String,
    pub usdc_mint: String,
    pub sign_with: Option<SigningKey>,
}

impl HelloSpec {
    pub fn new(key: &MmKey, instance_id: &str, channel: Channel) -> Self {
        Self {
            key: key.clone(),
            instance_id: instance_id.into(),
            channel: channel.as_str().into(),
            signed_channel: channel,
            version: json!(1),
            program_id: PROGRAM_ID.into(),
            usdc_mint: usdc_mint(),
            sign_with: None,
        }
    }

    pub fn frame(&self, challenge: &str) -> Value {
        let signer = self.sign_with.as_ref().unwrap_or(&self.key.signing);
        let sig = signer.sign(auth_message(self.signed_channel, challenge).as_bytes());
        json!({
            "type": "hello", "version": self.version, "channel": self.channel, "mm_pubkey": self.key.pubkey,
            "instance_id": self.instance_id, "program_id": self.program_id, "usdc_mint": self.usdc_mint,
            "signature": B64.encode(sig.to_bytes()),
        })
    }
}

/// Dials `path`, answers the challenge with `spec`; returns the socket and the first
/// reply (welcome or error).
pub async fn dial(server: &TestServer, path: &str, spec: &HelloSpec) -> (Ws, Value) {
    let (mut ws, _) = connect_async(server.ws_url(path)).await.unwrap();
    let challenge = next_json(&mut ws).await.unwrap();
    assert_eq!(challenge["type"], "challenge");
    let c = challenge["challenge"].as_str().unwrap().to_string();
    assert_eq!(c.len(), 64);
    assert!(challenge["server_time"].is_u64());
    send_json(&mut ws, &spec.frame(&c)).await;
    let reply = next_json(&mut ws).await.unwrap();
    (ws, reply)
}

