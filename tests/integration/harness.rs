type Log = Arc<Mutex<Vec<(Channel, Value)>>>;

pub struct FakeMm {
    log: Log,
    // Dropping a stop sender closes that channel's socket.
    _rfq_stop: mpsc::UnboundedSender<()>,
    sign_stop: Option<mpsc::UnboundedSender<()>>,
}

pub struct FakeMmBuilder {
    key: MmKey,
    instance_id: String,
    health: Value,
    on_rfq: Handler,
    on_sign: Handler,
}

impl FakeMm {
    pub fn builder(key: &MmKey, instance_id: &str) -> FakeMmBuilder {
        FakeMmBuilder {
            key: key.clone(),
            instance_id: instance_id.into(),
            health: desk_health(key, 200.0, 0.0),
            on_rfq: Arc::new(|_| Action::Ignore),
            on_sign: Arc::new(|_| Action::Ignore),
        }
    }

    /// Frames received on `channel` whose `type` is `ty` (and `method`, if given).
    pub fn received(&self, channel: Channel, ty: &str, method: Option<&str>) -> Vec<Value> {
        self.log
            .lock()
            .unwrap()
            .iter()
            .filter(|(c, v)| {
                *c == channel && v["type"] == ty && method.is_none_or(|m| v["method"] == m)
            })
            .map(|(_, v)| v.clone())
            .collect()
    }

    pub fn disconnect_sign(&mut self) {
        if let Some(s) = self.sign_stop.take() {
            let _ = s.send(());
        }
    }
}

impl FakeMmBuilder {
    pub fn health(mut self, body: Value) -> Self {
        self.health = body;
        self
    }

    /// Handles every non-health frame on ws/rfq.
    pub fn on_rfq(mut self, f: impl Fn(&Value) -> Action + Send + Sync + 'static) -> Self {
        self.on_rfq = Arc::new(f);
        self
    }

    pub fn on_sign(mut self, f: impl Fn(&Value) -> Action + Send + Sync + 'static) -> Self {
        self.on_sign = Arc::new(f);
        self
    }

    pub async fn connect(self, server: &TestServer) -> FakeMm {
        let log: Log = Arc::default();
        let health = self.health.clone();
        let on_rfq = self.on_rfq.clone();
        let rfq_handler: Handler = Arc::new(move |req| {
            if req["type"] == "market_request" && req["method"] == "health" {
                Action::Reply(market_ok(req, health.clone()))
            } else {
                on_rfq(req)
            }
        });
        let rfq_stop = self
            .channel(server, Channel::Rfq, rfq_handler, log.clone())
            .await;
        let sign_stop = self
            .channel(server, Channel::Sign, self.on_sign.clone(), log.clone())
            .await;
        FakeMm {
            log,
            _rfq_stop: rfq_stop,
            sign_stop: Some(sign_stop),
        }
    }

    async fn channel(
        &self,
        server: &TestServer,
        channel: Channel,
        handler: Handler,
        log: Log,
    ) -> mpsc::UnboundedSender<()> {
        let path = format!("/{}", channel.as_str());
        let (ws, welcome) = dial(
            server,
            &path,
            &HelloSpec::new(&self.key, &self.instance_id, channel),
        )
        .await;
        assert_eq!(welcome["type"], "welcome", "{welcome}");
        let (stop_tx, stop_rx) = mpsc::unbounded_channel();
        tokio::spawn(run_channel(ws, channel, handler, log, stop_rx));
        stop_tx
    }
}

async fn run_channel(
    mut ws: Ws,
    channel: Channel,
    handler: Handler,
    log: Log,
    mut stop: mpsc::UnboundedReceiver<()>,
) {
    let (out_tx, mut out_rx) = mpsc::unbounded_channel::<Value>();
    loop {
        tokio::select! {
            _ = stop.recv() => {
                let _ = ws.close(None).await;
                return;
            }
            Some(v) = out_rx.recv() => {
                if ws.send(Message::Text(v.to_string().into())).await.is_err() {
                    return;
                }
            }
            msg = ws.next() => match msg {
                Some(Ok(Message::Text(t))) => {
                    let Ok(v) = serde_json::from_str::<Value>(t.as_str()) else { continue };
                    log.lock().unwrap().push((channel, v.clone()));
                    match handler(&v) {
                        Action::Reply(r) => {
                            if ws.send(Message::Text(r.to_string().into())).await.is_err() {
                                return;
                            }
                        }
                        Action::ReplyAfter(d, r) => {
                            let tx = out_tx.clone();
                            tokio::spawn(async move {
                                tokio::time::sleep(d).await;
                                let _ = tx.send(r);
                            });
                        }
                        Action::Ignore => {}
                        Action::Disconnect => {
                            let _ = ws.close(None).await;
                            return;
                        }
                    }
                }
                Some(Ok(_)) => {}
                None | Some(Err(_)) => return,
            },
        }
    }
}

